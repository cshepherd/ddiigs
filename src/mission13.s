*----------------------------------------------------------
* Mission 1.3 — Compiled mission1 sprite bank
* Loaded into bank $1B by the engine. Holds AND/ORA-pipeline
* compiled versions of mission1 NPC frames so they can render
* through draw_sprite_compiled (≈half the cycles per byte vs
* the legacy mask-checking draw_sprite). Migration order:
* Williams first, then Linda/Roper/etc.
*
* Bank $1B picked because: $03-$10 are level backgrounds,
* $11 is SFX scratch, $12 is NTP player, $13-$16 are music
* data, $17 is PAK decompression scratch, $18 is the playfield
* shadow, $19 is mission12, and $1A holds boss SFX (BURNGONE
* + BURNBACK). $1B is the next free bank.
*
* Header layout mirrors mission1/mission12 so init_mission13
* can use the same offsets to find the sprite address table.
*----------------------------------------------------------
    org $1B0000

*==========================================================
* Header — only +$12 (spr_addr_off) is used by init_mission13.
*==========================================================
level_header
 ds $12                          ; +$00..+$11 reserved
spr_addr_off   dw spr_addr_tbl   ; +$12 offset to sprite address table

*-------------------------------
* Sprite pixel data address table (bank $1B addresses).
* init_mission13 reads each entry and stashes the address in
* a matching spr_* cache variable in game.s. Compiled sprites
* need 4 entries per frame: DATA, MASK, DATA_MIRROR, MASK_MIRROR.
* Order is stable — the engine reads entries by offset, so
* don't reorder without updating init_mission13.
*-------------------------------
