    org $020000

OP_NONE     EQU 0 ; NOP
OP_CLS      EQU 1 ; clear screen
OP_FADEIN   EQU 2 ; fade in
OP_FADEOUT  EQU 3 ; fade out
OP_TEXT     EQU 4 ; render text
OP_GFX      EQU 5 ; render graphics
OP_WAIT     EQU 6 ; wait
OP_PALETTE  EQU 7 ; set palette

; screens playlist
    dw SCREEN1          ; just text, "you win" etc
    hex 0000

