; go for broak
  HEX 00000000880887013e045e0c09070907
  HEX 00000000000000000000000000000000

; first (only) screen
SCREEN1
    db OP_CLS           ; clear screen
    db OP_PALETTE       ; set palette
    dw PALETTE01        ; params: palette data
    dw OP_GFX           ; render graphics
    dw BROAK            ; params: graphics data
    dw #20              ; params: x position (in bytes not nibbles)
    dw #1               ; params: y position
    db OP_TEXT          ; render text
    dw CUTSCENE11_TEXT  ; params: text display list
    db OP_FADEIN        ; fade in
    db OP_WAIT          ; wait
    dw 60*3             ; params: frames to wait
    db OP_FADEOUT       ; fade out
    hex ffff            ; end of screen

; text assets
CUTSCENE11_TEXT
    dw CUTSCENE11_TEXT1
    dw CUTSCENE11_TEXT2
    dw CUTSCENE11_TEXT3
    dw CUTSCENE11_TEXT4
    dw CUTSCENE11_TEXT5
    hex 0000

