* Mission 1.4 — Compiled armed-NPC sprite bank
* Loaded into bank $1C by the engine. Holds AND/ORA-pipeline
* compiled versions of armed Linda + armed Williams frames.
* Split out from mission13.s (bank $1B) because the regular
* + armed sprite set together exceeded a single 64KB bank.
*
* Bank $1C picked because $1B is mission13 (regular compiled
* NPCs), $1A holds boss SFX, and $1C is the next free bank.
