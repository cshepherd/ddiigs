*----------------------------------------------------------
* ProDOS 8 file loading and relocation
*----------------------------------------------------------

]IOBUF = $0C00         ; 1024-byte ProDOS I/O buffer (page-aligned)
]RDBUF = $0800         ; 1024-byte read buffer (= 2 disk blocks), $0800-$0BFF.
                       ; Lives well below title.s ($2000+) so growing
                       ; the binary can't overlap the disk-read window.

*----------------------------------------------------------
* load_ccc - Load CCC.SHR to bank $02 starting at $02/2000
*----------------------------------------------------------
 mx %11
load_ccc
 jsr $BF00
 dfb $C8              ; OPEN
 da ccc_open
 bcs :err
 lda ccc_oref
 sta ccc_rref
 sta ccc_cref

 lda #$00
 sta t_dest
 lda #$20
 sta t_dest+1          ; destination starts at $xx/2000
 lda #$02
 sta t_bank

:readlp
 jsr $BF00
 dfb $CA              ; READ
 da ccc_read
 bcs :close

 jsr copy_chunk_bank

* Advance destination by $1000
 lda t_dest+1
 clc
 adc #$04              ; advance dest by 1KB
 sta t_dest+1
 bcc :readlp
* Address wrapped — next bank
 lda #$00
 sta t_dest+1
 inc t_bank
 bra :readlp

:close
 php
 jsr $BF00
 dfb $CC              ; CLOSE
 da ccc_close
 plp
:err rts

*----------------------------------------------------------
* load_drugs - Load DRUGS.PAK and _UnPackBytes-decompress it
* to bank $02 starting at $02/2000. The updated drugs.shr art
* has lower entropy than the original so PackBytes RLE shrinks
* it substantially; we defer to load_titlentp_pak which already
* implements the load-PAK-into-$17/$2000 + multi-call unpack
* sequence used for NTPPLAYER/TITLE.NTP/SELECT.
*
* Decompressed image still lands at $02/2000..$02/9FFE (32 KB:
* pixels + SCBs + palette), so the downstream "copy $02/2000 →
* $01/2000" path needs no changes.
*----------------------------------------------------------
 mx %11
load_drugs
 lda #<drugs_path
 sta t2_open+1
 lda #>drugs_path
 sta t2_open+2
 lda #$02
 sta t_unpack_bank
 lda #$00
 sta t_unpack_offset
 lda #$20
 sta t_unpack_offset+1
 jsr load_titlentp_pak
 rts

*----------------------------------------------------------
* load_titlentp_pak - Load a TITLE.NTPx.PAK file to bank
* $17/$2000 via ProDOS, then call _UnPackBytes to decompress
* it to t_unpack_bank/$0000.
* Caller must set t2_open's pathname pointer (+1/+2) and
* t_unpack_bank before calling. Emulation mode on entry.
*----------------------------------------------------------
load_titlentp_pak
 jsr $BF00
 dfb $C8              ; OPEN
 da t2_open
 bcc :ok
 jmp :err
:ok
 lda t2_oref
 sta t2_rref
 sta t2_cref
 sta t_eofref

* Capture file size for the UnPackBytes source-length param.
 jsr $BF00
 dfb $D1              ; GET_EOF
 da t_get_eof
 lda t_eof_size
 sta t_file_size
 lda t_eof_size+1
 sta t_file_size+1

* Read PAK into bank $17 starting at $2000, 1KB chunks.
 lda #$00
 sta t_dest
 lda #$20
 sta t_dest+1
 lda #$17
 sta t_bank

:readlp
 jsr $BF00
 dfb $CA              ; READ
 da t2_read
 bcs :close
 jsr copy_chunk_bank
 lda t_dest+1
 clc
 adc #$04              ; advance dest by 1KB
 sta t_dest+1
 bcc :readlp
 lda #$00
 sta t_dest+1
 inc t_bank
 bra :readlp

:close
 jsr $BF00
 dfb $CC              ; CLOSE
 da t2_close

* Unpack from $17/$2000 to t_unpack_bank/t_unpack_offset via a
* multi-call _UnPackBytes loop. The ROM's destSize counter is
* 16-bit so each call writes at most $FFFF bytes, but it
* returns RESULT = bytes consumed from input and writes the
* updated dest long pointer back to *t_unpack_addr (carrying
* into the bank byte). We resume the source by advancing
* t_src_addr/t_src_size by RESULT and looping.
 clc
 xce                   ; native mode
 rep $30

* Initialise the long dest pointer once. The ROM updates it
* in place across calls, so subsequent iterations pick up at
* the next byte to write.
 lda t_unpack_offset
 sta t_unpack_addr
 lda t_unpack_bank
 and #$00FF
