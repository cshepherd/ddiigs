:err rts

*----------------------------------------------------------
* load_titlentp_pak - Load a TITLE.NTPx.PAK file to bank
* $17/$2000 via ProDOS, then call _UnPackBytes to decompress
* it to t_unpack_bank/$0000.
* Caller must set t2_open's pathname pointer (+1/+2) and
* t_unpack_bank before calling. Emulation mode on entry.
*----------------------------------------------------------
load_titlentp_pak
 jsr $BF00
 dfb $C8              ; OPEN
 da t2_open
 bcc :ok
 jmp :err
:ok
 lda t2_oref
 sta t2_rref
 sta t2_cref
 sta t_eofref

* Capture file size for the UnPackBytes source-length param.
 jsr $BF00
 dfb $D1              ; GET_EOF
 da t_get_eof
 lda t_eof_size
 sta t_file_size
 lda t_eof_size+1
 sta t_file_size+1

* Read PAK into bank $17 starting at $2000, 4KB chunks.
 lda #$00
 sta t_dest
 lda #$20
 sta t_dest+1
 lda #$17
 sta t_bank

:readlp
 jsr $BF00
 dfb $CA              ; READ
 da t2_read
 bcs :close
 jsr copy_chunk_bank
 lda t_dest+1
 clc
 adc #$10
 sta t_dest+1
 bcc :readlp
 lda #$00
 sta t_dest+1
 inc t_bank
 bra :readlp

:close
 jsr $BF00
 dfb $CC              ; CLOSE
 da t2_close

* Unpack from $17/$2000 to t_unpack_bank/t_unpack_offset via a
* multi-call _UnPackBytes loop. The ROM's destSize counter is
* 16-bit so each call writes at most $FFFF bytes, but it
* returns RESULT = bytes consumed from input and writes the
* updated dest long pointer back to *t_unpack_addr (carrying
* into the bank byte). We resume the source by advancing
* t_src_addr/t_src_size by RESULT and looping.
 clc
 xce                   ; native mode
 rep $30

* Initialise the long dest pointer once. The ROM updates it
* in place across calls, so subsequent iterations pick up at
* the next byte to write.
 lda t_unpack_offset
 sta t_unpack_addr
 lda t_unpack_bank
 and #$00FF
 sta t_unpack_addr+2

* Initialise source low word and remaining bytes. PAK lives
* in bank $17 (its bank byte is hard-coded in the PEA below),
* file size came from GET_EOF.
 lda #$2000
 sta t_src_addr
 lda t_file_size
 sta t_src_size

:unpack_loop
 lda t_src_size
 beq :unpack_done

 lda #$ffff
 sta t_unpack_size

 pha                   ; result space
 pea $0017             ; src bank
