 and #$0F00
 xba                   ; swap bytes: red nibble now in low byte
 asl
 asl
 asl
 asl                   ; * 16
 clc
 adc :step
 tay
 sep $20
 lda fadeBlack,y       ; faded R value (8-bit, 0-F)
 sta :fadedR
 rep $20
* Combine $0RGB from :fadedR (R), :fadedGB (G+B)
 lda :fadedR
 and #$000F            ; $000R
 xba                   ; $0R00
 sta :fadedRGB         ; save R in high byte position
 lda :fadedGB
 and #$00FF            ; $00GB
 ora :fadedRGB         ; $0RGB
 stal $019E00,x        ; write to palette RAM

 inx
 inx
