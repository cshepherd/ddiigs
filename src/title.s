* Toggle the blue Japanese writing on/off via palette swap.
* TITLE_MERGED stores per-pixel "writing or II underneath" indices
* in $1-$5 and $C-$E. writing_on points each at its writing colour;
* writing_off points each at the II colour beneath that pixel (or
* zero for writing pixels that extend past the II body), so the
* off state is pixel-exact with no outline ghosts.
* Pair table (W=writing color in TITLE7, B=II color underneath):
*   $1: B/0   $2: F/0   $3: 8/0   $4: B/8   $5: B/6
*   $C: B/7   $D: F/8   $E: F/6
* Generated by tools/merge_sprites.py.
writing_on
  mx %00
  lda #$06AE
  stal $E19E02         ; $1: writing-blue
  lda #$020A
  stal $E19E04         ; $2: writing-highlight
  lda #$06AE           ; was $0DC4 (TITLE7's gold edge); recoloured
  stal $E19E06         ; $3: writing-blue (override gold fringing)
  stal $E19E08         ; $4: writing-blue
  stal $E19E0A         ; $5: writing-blue
  stal $E19E18         ; $C: writing-blue
  lda #$020A
  stal $E19E1A         ; $D: writing-highlight
  stal $E19E1C         ; $E: writing-highlight
  rts

writing_off
  mx %00
  lda #$0000
  stal $E19E02         ; $1 -> 0 (writing-blue over BG)
  stal $E19E04         ; $2 -> 0 (writing-highlight over BG)
  stal $E19E06         ; $3 -> 0 (writing red-edge over BG)
  lda #$0DC4
  stal $E19E08         ; $4 -> $8 (II red)
  stal $E19E1A         ; $D -> $8 (II red)
  lda #$0FFF
  stal $E19E0A         ; $5 -> $6 (II white)
  stal $E19E1C         ; $E -> $6 (II white)
  lda #$0D31
  stal $E19E18         ; $C -> $7 (II red-orange)
  rts

