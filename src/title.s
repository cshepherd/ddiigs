 da drugs_open
 bcs :err
 lda drugs_oref
 sta drugs_rref
 sta drugs_cref

 lda #$00
 sta t_dest
 lda #$20
 sta t_dest+1          ; destination starts at $xx/2000
 lda #$02
 sta t_bank

:readlp
 jsr $BF00
 dfb $CA              ; READ
 da drugs_read
 bcs :close

 jsr copy_chunk_bank

 lda t_dest+1
 clc
 adc #$10
 sta t_dest+1
 bcc :readlp
 lda #$00
 sta t_dest+1
 inc t_bank
 bra :readlp

:close
 php
 jsr $BF00
